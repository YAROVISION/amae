def create_cross_references():
    base_dir = "/Users/kostantinkrivula/Desktop/amae/segments"
    all_files = glob.glob(os.path.join(base_dir, "*.md"))
    
    # build a reverse map: category -> list of emotions (files)
    category_map = {}
    for filename in all_files:
        basename = os.path.basename(filename)
        name = basename[:-3] # remove .md
        
        # some names are a bit different, let's normalize to match dict
        # wait, the dict keys exactly match the segment basenames!
        if name in classification_data:
            abstractness, valence = classification_data[name]
            cat_key = (abstractness, valence)
            if cat_key not in category_map:
                category_map[cat_key] = []
            category_map[cat_key].append(basename)
        else:
            print(f"Warning: {name} not found in classification data")
            
    # now inject links
    for filename in all_files:
        basename = os.path.basename(filename)
        name = basename[:-3]
        
        if name not in classification_data:
            continue
            
        abstractness, valence = classification_data[name]
        cat_key = (abstractness, valence)
        
        # related emotions
        related = [f"[{f[:-3]}](./{f})" for f in category_map[cat_key] if f != basename]
        
        with open(filename, 'r', encoding='utf-8') as f:
            content = f.read()
            
        # check if already injected
        if "> **Класифікація:**" in content:
            continue
            
        # create the metadata block
        metadata_block = f"""\n\n---
> **Класифікація:**
> - **Рівень абстрактності:** {abstractness}
> - **Валентність:** {valence}
> 
> 🔗 [Повна класифікація емоцій](../Emotions_Classification.md)
"""
        if related:
            metadata_block += f"> 🔗 **Схожі емоції у цій категорії:** {', '.join(related)}\n"
            
        # append to file
        with open(filename, 'w', encoding='utf-8') as f:
            f.write(content.strip() + metadata_block)
            
    print("Cross-references added successfully!")

if __name__ == "__main__":
    create_cross_references()
